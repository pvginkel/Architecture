export type LayerId =
  | "infrastructure"
  | "platform"
  | "delivery"
  | "capabilities";

export type Status = "active" | "dev" | "legacy" | "unclear" | "out-of-band";

export type CapabilityId =
  | "compute"
  | "networking"
  | "storage"
  | "identity"
  | "observability"
  | "delivery"
  | "developer-tools"
  | "ai-rag"
  | "home-automation"
  | "media"
  | "personal-apps";

export type EdgeType =
  | "runs-on"
  | "deploys"
  | "builds"
  | "pulls-image"
  | "routes"
  | "stores-data"
  | "authenticates"
  | "gets-secrets"
  | "observes";

export interface ArchitectureLayer {
  id: LayerId;
  label: string;
  y: number;
  height: number;
  summary: string;
}

export interface NodeStats extends Record<string, unknown> {
  sourceRepo?: string;
  version?: string;
  introduced?: string;
  loc?: string;
}

export interface ArchitectureNode extends Record<string, unknown> {
  id: string;
  label: string;
  kind: string;
  layer: LayerId;
  capability: CapabilityId;
  status: Status;
  summary: string;
  logo?: string;
  stats?: NodeStats;
  position: {
    x: number;
    y: number;
  };
}

export interface ArchitectureEdge extends Record<string, unknown> {
  id: string;
  source: string;
  target: string;
  type: EdgeType;
  label: string;
  strength: "primary" | "secondary";
}

